/**
 * Completeness gate (CLI) — is every closed subtopic's fact universe 100%
 * taught and 100% drilled?
 *
 * Runs the shared `completeness` rule (`auditAllCompleteness` in
 * `src/content/validate.ts`), prints one row per subtopic
 * (subtopic | facts | taught% | drilled% | high-yield MCQ% | status), and writes
 * `.research/completeness/STATUS.md` with a per-subject summary plus the QUEUE
 * of subtopics that have no `content/facts/<id>.json` yet, in study order
 * (`content/plan/units.json`, then `learning-sequence.json`, then the rest).
 *
 * EXIT CODE: non-zero when any subtopic WITH a facts file is below 100% taught,
 * 100% drilled, or 100% high-yield-with-MCQ (or a facts file names a subtopic with no content), so a
 * completed subtopic can never regress — AND when any subtopic has NO facts file:
 * all 129 universes are closed, so there is no backlog allowance any more. `npm run check` chains this after
 * `validate:content`.
 *
 * Flags (used by the tests to run against fixtures):
 *   --content-dir <dir>  content root to audit (default: ./content)
 *   --out <file>         STATUS.md path (default: .research/completeness/STATUS.md)
 *   --verbose            print every finding, not only the per-subtopic table
 *
 * Run via `npm run audit:completeness`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  auditAllCompleteness,
  completenessExitCode,
  type CompletenessRow,
} from '../src/content/validate';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Value of `--flag <value>`, or undefined. */
function argValue(flag: string): string | undefined {
  const i = process.argv.indexOf(flag);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const contentDir = resolve(argValue('--content-dir') ?? resolve(ROOT, 'content'));
const outFile = resolve(argValue('--out') ?? resolve(ROOT, '.research/completeness/STATUS.md'));
const verbose = process.argv.includes('--verbose');

const report = auditAllCompleteness(contentDir);
const exitCode = completenessExitCode(report);

/* ----- Optional taxonomy labels (subtopic names, subject names) ----------- */

const subtopicName = new Map<string, string>();
const subjectName = new Map<string, string>();
const taxonomyPath = resolve(contentDir, 'taxonomy.json');
if (existsSync(taxonomyPath)) {
  try {
    const t = JSON.parse(readFileSync(taxonomyPath, 'utf8')) as {
      subjects?: { code: string; name: string }[];
      subtopics?: { id: string; name: string }[];
    };
    for (const s of t.subjects ?? []) subjectName.set(s.code, s.name);
    for (const s of t.subtopics ?? []) subtopicName.set(s.id, s.name);
  } catch {
    /* labels are cosmetic */
  }
}

/* ----- Console table ------------------------------------------------------- */

const pct = (n: number | undefined): string => (n === undefined ? '—' : `${n}%`);
const ratio = (r: number | undefined): string => (r === undefined ? '—' : r.toFixed(2));

const header = ['subtopic', 'facts', 'taught%', 'drilled%', 'high-yield MCQ%', 'status'];
const tableRows = report.rows.map((r) =>
  r.hasFacts
    ? [r.subtopicId, String(r.result!.facts), pct(r.result!.taughtPct), pct(r.result!.drilledPct), pct(r.result!.highYieldMcqPct), r.status]
    : [r.subtopicId, `~${r.estimate ?? 0}`, '—', '—', '—', `${r.status} (retrieval ${ratio(r.retrievalRatio)})`],
);
const widths = header.map((h, i) => Math.max(h.length, ...tableRows.map((row) => row[i]!.length)));
const line = (cells: string[]): string => cells.map((c, i) => c.padEnd(widths[i]!)).join(' | ');
console.log(line(header));
console.log(widths.map((w) => '-'.repeat(w)).join('-|-'));
// Closed subtopics first (they are the gate), then the backlog in study order.
for (const row of [...tableRows.filter((_, i) => report.rows[i]!.hasFacts), ...tableRows.filter((_, i) => !report.rows[i]!.hasFacts)]) {
  console.log(line(row));
}

if (verbose || exitCode !== 0) {
  for (const f of report.findings) console.log(`  ✗ [${f.rule}] ${f.subtopicId}/${f.factId}: ${f.detail}`);
}
for (const id of report.orphanFacts) console.log(`  ✗ [facts-orphan] ${id}: facts file but the subtopic has no notes/MCQs/cards`);

/* ----- STATUS.md ----------------------------------------------------------- */

const closed = report.rows.filter((r) => r.hasFacts);
const backlog = report.rows.filter((r) => !r.hasFacts);
const subjects = [...new Set(report.rows.map((r) => r.subjectCode))];

const md: string[] = [];
md.push('# Completeness status');
md.push('');
md.push(
  'Generated by `npm run audit:completeness`. A subtopic is COMPLETE when every fact in `content/facts/<id>.json` is ' +
    'taught (key tokens in its `taughtIn` note) and drilled (>= 1 MCQ/card asking it; high-yield facts need an MCQ). ' +
    'Subtopics without a facts file show an ESTIMATED fact count (distinct bolded terms + keyPoints) and the retrieval ' +
    'ratio (MCQs + cards) / estimate.',
);
md.push('');
md.push(`Gate: **${exitCode === 0 ? 'PASS' : 'FAIL'}** — ${closed.length} closed subtopic(s), ${backlog.length} without a facts file.`);
md.push('');
md.push('## Per subject');
md.push('');
md.push('| Subject | Subtopics | With facts | Complete | Facts (closed) | Est. facts (backlog) | MCQs + cards (backlog) | Backlog retrieval ratio |');
md.push('|---|---|---|---|---|---|---|---|');
for (const code of subjects) {
  const rows = report.rows.filter((r) => r.subjectCode === code);
  const withFacts = rows.filter((r) => r.hasFacts);
  const open = rows.filter((r) => !r.hasFacts);
  const est = open.reduce((n, r) => n + (r.estimate ?? 0), 0);
  const items = open.reduce((n, r) => n + r.mcqs + r.cards, 0);
  md.push(
    `| ${code}${subjectName.has(code) ? ` (${subjectName.get(code)})` : ''} | ${rows.length} | ${withFacts.length} | ` +
      `${withFacts.filter((r) => r.status === 'COMPLETE').length} | ${withFacts.reduce((n, r) => n + r.result!.facts, 0)} | ` +
      `${est} | ${items} | ${est > 0 ? (items / est).toFixed(2) : '—'} |`,
  );
}
md.push('');
md.push('## Closed subtopics');
md.push('');
if (closed.length === 0) md.push('_None yet._');
else {
  md.push('| Subtopic | Facts | Taught | Drilled | High-yield MCQ | Status |');
  md.push('|---|---|---|---|---|---|');
  for (const r of closed) {
    const c = r.result!;
    md.push(
      `| ${r.subtopicId} | ${c.facts} | ${c.taught}/${c.facts} (${c.taughtPct}%) | ${c.drilled}/${c.facts} (${c.drilledPct}%) | ` +
        `${c.highYieldMcq}/${c.highYield} (${c.highYieldMcqPct}%) | ${r.status} |`,
    );
  }
}
if (report.findings.length > 0) {
  md.push('');
  md.push('### Findings');
  md.push('');
  for (const f of report.findings) md.push(`- \`${f.rule}\` ${f.subtopicId}/${f.factId}: ${f.detail}`);
}
md.push('');
md.push('## Queue — subtopics with no facts file (study order)');
md.push('');
md.push('Order: `content/plan/units.json`, then `content/plan/learning-sequence.json`, then unsequenced subtopics.');
md.push('');
md.push('| # | Subtopic | Subject | Est. facts | MCQs | Cards | Retrieval ratio |');
md.push('|---|---|---|---|---|---|---|');
backlog.forEach((r: CompletenessRow, i) => {
  const name = subtopicName.get(r.subtopicId);
  md.push(
    `| ${i + 1} | ${r.subtopicId}${name ? ` — ${name}` : ''}${r.order === Number.MAX_SAFE_INTEGER ? ' _(unsequenced)_' : ''} | ` +
      `${r.subjectCode} | ${r.estimate ?? 0} | ${r.mcqs} | ${r.cards} | ${ratio(r.retrievalRatio)} |`,
  );
});
md.push('');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, md.join('\n'));

console.log('');
console.log(`wrote ${outFile}`);
console.log(
  `completeness: ${closed.length} closed (${closed.filter((r) => r.status === 'COMPLETE').length} COMPLETE), ` +
    `${backlog.length} in the queue (~${backlog.reduce((n, r) => n + (r.estimate ?? 0), 0)} estimated facts)`,
);
if (exitCode !== 0) {
  console.error(
    backlog.length > 0
      ? `\n✗ completeness gate FAILED: ${backlog.length} subtopic(s) have no facts file (every subtopic must be closed)`
      : '\n✗ completeness gate FAILED: a subtopic with a facts file is below 100% taught, drilled, or high-yield-with-MCQ',
  );
  process.exit(exitCode);
}
console.log('\n✓ completeness gate passed');
